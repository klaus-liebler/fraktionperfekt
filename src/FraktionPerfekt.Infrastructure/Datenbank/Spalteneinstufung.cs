namespace FraktionPerfekt.Infrastructure.Datenbank;

/// <summary>Einstufung einer Spalte (Datenbank-Regeln, Regel 1).</summary>
public enum Spaltenart
{
    /// <summary>Führendes Datum einer Stammdaten-Entität (Identität, Schlüssel, nicht veränderliche Angaben).</summary>
    Stammdatum,

    /// <summary>Spalte einer bitemporalen Versionstabelle.</summary>
    Version,

    /// <summary>Datum eines fachlichen Vorgangs (Antrag, Termin, Sitzung, Aufgabe …), Änderungen im Protokoll.</summary>
    Vorgang,

    /// <summary>Bewusst eingefrorener Belegwert (z. B. Empfänger einer versandten Mail, Spender auf der Quittung).</summary>
    Beleg,

    /// <summary>Nur nach Anonymisierung gefüllte grobe Angabe für Statistiken.</summary>
    Anonymisierungsrest,

    /// <summary>Übergang: Kopie aus einer anderen Tabelle oder Version – verboten, entfällt im Umbau.</summary>
    Kopie,

    /// <summary>Übergang: Liste bzw. Struktur als Text in einer Spalte – verboten, wird eigene Tabelle.</summary>
    Json,
}

